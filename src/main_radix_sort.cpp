unsigned int bit_ceil(unsigned int num) {
    assert(num != 0);
    unsigned int out = 1;

    while(num != 0) {
        out <<= 1;
        num >>= 1;
    }

    return out;
}

unsigned int optimal_group_size(int grid_size) {
    return GROUP_SIZE;
}

void prefix_sum(const gpu::gpu_mem_32u& input_gpu, gpu::gpu_mem_32u& buffer, unsigned int n, unsigned int bit) {
    cuda::copy_mem_bit(gpu::WorkSize(GROUP_SIZE, n), input_gpu, buffer, n, n, bit);

    unsigned int offset = 0;
    for(unsigned int in_size = n; in_size > SMALL_ARRAY_SIZE; in_size >>= 1) {
        cuda::prefix_sum_01_reduction(gpu::WorkSize(optimal_group_size(in_size >> 1), in_size >> 1), buffer, buffer, in_size, offset, offset + in_size);
        offset += in_size;
    }

    cuda::small_array_prefix(gpu::WorkSize(SMALL_ARRAY_SIZE, SMALL_ARRAY_SIZE), buffer, SMALL_ARRAY_SIZE, offset);

    for(unsigned int in_size = SMALL_ARRAY_SIZE; in_size < n; in_size <<= 1) {
        const unsigned int out_size = in_size << 1;
        cuda::prefix_sum_02_prefix_accumulation(gpu::WorkSize(optimal_group_size(in_size), in_size), buffer, buffer, in_size, offset, offset - out_size);
        offset -= out_size;
    }
}

void run(int argc, char** argv)
{
    // chooseGPUVkDevices:
    // - Если не доступо ни одного устройства - кинет ошибку
    // - Если доступно ровно одно устройство - вернет это устройство
    // - Если доступно N>1 устройства:
    //   - Если аргументов запуска нет или переданное число не находится в диапазоне от 0 до N-1 - кинет ошибку
    //   - Если аргумент запуска есть и он от 0 до N-1 - вернет устройство под указанным номером
    gpu::Device device = gpu::chooseGPUDevice(gpu::selectAllDevices(ALL_GPUS, true), argc, argv);

    gpu::Context context = activateContext(device, gpu::Context::TypeCUDA);
    // OpenCL - рекомендуется как вариант по умолчанию, можно выполнять на CPU, есть printf, есть аналог valgrind/cuda-memcheck - https://github.com/jrprice/Oclgrind
    // CUDA   - рекомендуется если у вас NVIDIA видеокарта, есть printf, т.к. в таком случае вы сможете пользоваться профилировщиком (nsight-compute) и санитайзером (compute-sanitizer, это бывший cuda-memcheck)
    // Vulkan - не рекомендуется, т.к. писать код (compute shaders) на шейдерном языке GLSL на мой взгляд менее приятно чем в случае OpenCL/CUDA
    //          если же вас это не останавливает - профилировщик (nsight-systems) при запуске на NVIDIA тоже работает (хоть и менее мощный чем nsight-compute)
    //          кроме того есть debugPrintfEXT(...) для вывода в консоль с видеокарты
    //          кроме того используемая библиотека поддерживает rassert-проверки (своеобразные инварианты с уникальным числом) на видеокарте для Vulkan

    FastRandom r;

    int n = 100*1000*1000;
    int max_value = std::numeric_limits<int>::max();
    std::vector<unsigned int> as(n, 0);
    std::vector<unsigned int> sorted(n, 0);
    for (size_t i = 0; i < n; ++i) {
        as[i] = r.next(0, max_value);
    }
    std::cout << "n=" << n << " max_value=" << max_value << std::endl;

    {
        // убедимся что в массиве есть хотя бы несколько повторяющихся значений
        size_t force_duplicates_attempts = 3;
        bool all_attempts_missed = true;
        for (size_t k = 0; k < force_duplicates_attempts; ++k) {
            size_t i = r.next(0, n - 1);
            size_t j = r.next(0, n - 1);
            if (i != j) {
                as[j] = as[i];
                all_attempts_missed = false;
            }
        }
        rassert(!all_attempts_missed, 4353245123412);
    }

    {
        sorted = as;
        std::cout << "sorting on CPU..." << std::endl;
        timer t;
        std::sort(sorted.begin(), sorted.end());
        double elapsed = t.elapsed();
        // Вычисляем достигнутую эффективную пропускную способность видеопамяти (из соображений что мы отработали в один проход - считали массив и сохранили его переупорядоченным)
        double memory_size_gb = sizeof(unsigned int) * 2 * n / 1024.0 / 1024.0 / 1024.0;
        std::cout << "CPU std::sort finished in " << elapsed << " sec" << std::endl;
        std::cout << "CPU std::sort effective RAM bandwidth: " << memory_size_gb / elapsed << " GB/s (" << n / 1e6 / elapsed << " uint millions/s)" << std::endl;
    }

    // Аллоцируем буферы в VRAM
    const unsigned int rounded_n = bit_ceil(n);
    unsigned int buffer_offset = rounded_n - n;
    gpu::gpu_mem_32u input_gpu(n), out_buffer1(2*rounded_n), out_buffer2(2*rounded_n), pref_buffer(2*rounded_n);

    gpu::gpu_mem_32u* out1 = &out_buffer1;
    gpu::gpu_mem_32u* out2 = &out_buffer2;

    // Прогружаем входные данные по PCI-E шине: CPU RAM -> GPU VRAM
    input_gpu.writeN(as.data(), n);
    assert(n >= GROUP_SIZE);

    // Запускаем кернел (несколько раз и с замером времени выполнения)
    std::vector<double> times;
    for (int iter = 0; iter < 10; ++iter) {
        timer t;

        cuda::copy_mem(gpu::WorkSize(GROUP_SIZE, rounded_n), input_gpu, *out1, n, rounded_n);

        for(uint i = 0; i < 31; i++) {
            prefix_sum(*out1, pref_buffer, rounded_n, i);
            cuda::insert_to_sort_position(gpu::WorkSize(GROUP_SIZE, rounded_n), *out1, pref_buffer, *out2, rounded_n, i);
            std::swap(out1, out2);
        }

        times.push_back(t.elapsed());
    }
    std::cout << "GPU radix-sort times (in seconds) - " << stats::valuesStatsLine(times) << std::endl;

    // Вычисляем достигнутую эффективную пропускную способность видеопамяти (из соображений что мы отработали в один проход - считали массив и сохранили его переупорядоченным)
    double memory_size_gb = sizeof(unsigned int) * 2 * n / 1024.0 / 1024.0 / 1024.0;
    std::cout << "GPU radix-sort median effective VRAM bandwidth: " << memory_size_gb / stats::median(times) << " GB/s (" << n / 1e6 / stats::median(times) << " uint millions/s)" << std::endl;

    // Считываем результат по PCI-E шине: GPU VRAM -> CPU RAM
    std::vector<unsigned int> gpu_sorted = out1->readVector();

    // Сверяем результат
    for (size_t i = 0; i < n; ++i) {
        unsigned int index = i + buffer_offset;
        rassert(sorted[i] == gpu_sorted[index], 566324523452323, sorted[i], gpu_sorted[index], i);
    }

    // Проверяем что входные данные остались нетронуты (ведь мы их переиспользуем от итерации к итерации)
    std::vector<unsigned int> input_values = input_gpu.readVector();
    for (size_t i = 0; i < n; ++i) {
        rassert(input_values[i] == as[i], 6573452432, input_values[i], as[i]);
    }
}

int main(int argc, char** argv)
{
    int exit_code = 0;
    try {
        run(argc, argv);
    } catch (std::exception& e) {
        std::cerr << "Error: " << e.what() << std::endl;
        if (e.what() == DEVICE_NOT_SUPPORT_API) {
            // Возвращаем exit code = 0 чтобы на CI не было красного крестика о неуспешном запуске из-за выбора CUDA API (его нет на процессоре - т.е. в случае CI на GitHub Actions)
            exit_code = 0;
        } else if (e.what() == CODE_IS_NOT_IMPLEMENTED) {
            // Возвращаем exit code = 0 чтобы на CI не было красного крестика о неуспешном запуске из-за того что задание еще не выполнено
            exit_code = 0;
        } else {
            // Выставляем ненулевой exit code, чтобы сообщить, что случилась ошибка
            exit_code = 1;
        }
    }

    // we need to gracefully clear Vulkan context before it is too late (otherwise we encounter segfault on some systems)
    avk2::InstanceContext::clearGlobalInstanceContext();

    return exit_code;
}
